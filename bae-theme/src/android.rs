//! The theme as Kotlin for Compose, and the launch window's colour resources.

use std::fmt::Write;

use crate::{Argb, Roles, Theme};

/// The Kotlin file, named relative to the output directory.
pub const KOTLIN_FILE: &str = "kotlin/fm/bae/app/ui/appearance/ThemePalette.kt";

/// The launch window's background before Compose draws, as resource files
/// named relative to the output directory: the standard tone in each
/// appearance.
pub fn launch_resources(theme: &Theme) -> Result<Vec<(String, String)>, String> {
    let tone = &theme.tones[theme.standard.tone];
    [("values", &tone.surfaces.light), ("values-night", &tone.surfaces.dark)]
        .into_iter()
        .map(|(qualifier, surfaces)| {
            let background = surfaces
                .get("background")
                .ok_or_else(|| format!("tone {} has no `background` for the launch window", tone.name))?;
            Ok((
                format!("res/{qualifier}/theme_colors.xml"),
                format!(
                    "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n\
                     <!-- Generated by theme-gen from design/theme.toml; edit that file instead. -->\n\
                     <resources>\n    <color name=\"appearance_launch_background\">#{:08X}</color>\n</resources>\n",
                    background.0
                ),
            ))
        })
        .collect()
}

pub fn kotlin(theme: &Theme) -> String {
    let mut out = String::new();
    write_kotlin(&mut out, theme).expect("writing to a String does not fail");
    out
}

/// The theme as Kotlin, written to `out`.
fn write_kotlin(out: &mut String, theme: &Theme) -> std::fmt::Result {
    out.push_str(
        "// Generated by theme-gen from design/theme.toml; edit that file instead.\n\n\
         package fm.bae.app.ui.appearance\n\n\
         import androidx.compose.ui.graphics.Color\n\
         import androidx.compose.ui.text.TextStyle\n\
         import androidx.compose.ui.text.font.FontFamily\n\
         import androidx.compose.ui.text.font.FontWeight\n\
         import androidx.compose.ui.unit.dp\n\
         import androidx.compose.ui.unit.sp\n",
    );
    choice_enum(
        out,
        "SurfaceTone",
        theme.tones.iter().map(|tone| tone.name.as_str()),
        &theme.tones[theme.standard.tone].name,
    )?;
    choice_enum(
        out,
        "AccentChoice",
        theme.accents.iter().map(|accent| accent.name.as_str()),
        &theme.accents[theme.standard.accent].name,
    )?;

    roles_class(
        out,
        "One tone's surfaces in one appearance.",
        "ToneSurfaces",
        &theme.tones[0].surfaces.light,
    )?;
    out.push_str(
        "\n/** One accent's colours: text and glyphs in each appearance, and the fill behind white button labels. */\n\
         class AccentColors(\n    val dark: Color,\n    val fill: Color,\n    val light: Color,\n)\n",
    );
    roles_class(
        out,
        "Colours that mean the same in every tone, in one appearance.",
        "SemanticColors",
        &theme.semantics.light,
    )?;

    out.push_str("\nfun SurfaceTone.surfaces(dark: Boolean): ToneSurfaces =\n    when (this) {\n");
    for tone in &theme.tones {
        writeln!(out, "        SurfaceTone.{} ->", tone.name.to_uppercase())?;
        writeln!(out, "            if (dark) {{")?;
        roles_value(out, "ToneSurfaces", &tone.surfaces.dark, 16)?;
        writeln!(out, "            }} else {{")?;
        roles_value(out, "ToneSurfaces", &tone.surfaces.light, 16)?;
        writeln!(out, "            }}")?;
    }
    out.push_str("    }\n");

    out.push_str("\nval AccentChoice.colors: AccentColors\n    get() =\n        when (this) {\n");
    for accent in &theme.accents {
        writeln!(
            out,
            "            AccentChoice.{} ->",
            accent.name.to_uppercase()
        )?;
        let roles: Roles = [
            ("light", accent.light),
            ("dark", accent.dark),
            ("fill", accent.fill),
        ]
        .into_iter()
        .map(|(name, colour)| (name.to_string(), colour))
        .collect();
        roles_value(out, "AccentColors", &roles, 16)?;
    }
    out.push_str("        }\n");

    out.push_str("\nfun semanticColors(dark: Boolean): SemanticColors =\n    if (dark) {\n");
    roles_value(out, "SemanticColors", &theme.semantics.dark, 8)?;
    out.push_str("    } else {\n");
    roles_value(out, "SemanticColors", &theme.semantics.light, 8)?;
    out.push_str("    }\n");

    out.push_str(
        "\n/** How opaque a colour is laid over what is behind it. */\nobject ThemeOpacity {\n",
    );
    for (role, value) in &theme.opacity {
        writeln!(out, "    const val {role}: Float = {value:?}f")?;
    }
    out.push_str("}\n");

    out.push_str(
        "\n/** A text style, and whether it is set in capitals. */\n\
         class ThemeText(\n    val style: TextStyle,\n    val uppercase: Boolean,\n) {\n    companion object {\n",
    );
    for (role, text) in &theme.text {
        let family = if text.monospaced {
            "FontFamily.Monospace"
        } else {
            "FontFamily.Default"
        };
        writeln!(
            out,
            "        val {role} =\n            ThemeText(\n                TextStyle(\n                    \
             fontSize = {}.sp,\n                    fontWeight = {},\n                    \
             letterSpacing = ({}).sp,\n                    fontFamily = {family},\n                ),\n                \
             uppercase = {},\n            )",
            text.android,
            text.weight.kotlin(),
            text.tracking,
            text.uppercase
        )?;
    }
    out.push_str("    }\n}\n");

    out.push_str("\n/** Gaps and insets. */\nobject ThemeSpace {\n");
    for (role, value) in &theme.space {
        writeln!(out, "    val {role} = {value}.dp")?;
    }
    out.push_str("}\n\n/** Glyph sizes. */\nobject ThemeIcon {\n");
    for (role, icon) in &theme.icon {
        writeln!(out, "    val {role} = {}.dp", icon.sizes.android)?;
    }
    out.push_str("}\n\n/** Sizes that recur across screens. */\nobject ThemeSize {\n");
    for (role, lengths) in &theme.size {
        writeln!(out, "    val {role} = {}.dp", lengths.android)?;
    }
    out.push_str("}\n");

    out.push_str("\n/** Corner radii. */\nobject ThemeRadius {\n");
    for (role, value) in &theme.radius {
        writeln!(out, "    val {role} = {value}.dp")?;
    }
    out.push_str("}\n");
    Ok(())
}

/// The choices in the order the settings offer them, and the standard one.
fn choice_enum<'a>(
    out: &mut String,
    name: &str,
    entries: impl Iterator<Item = &'a str>,
    standard: &str,
) -> std::fmt::Result {
    writeln!(out, "\nenum class {name} {{")?;
    for entry in entries {
        writeln!(out, "    {},", entry.to_uppercase())?;
    }
    writeln!(
        out,
        "    ;\n\n    companion object {{\n        \
         /** What a new installation shows until the person chooses. */\n        \
         val STANDARD = {}\n    }}\n}}",
        standard.to_uppercase()
    )
}

fn roles_class(out: &mut String, doc: &str, name: &str, roles: &Roles) -> std::fmt::Result {
    writeln!(out, "\n/** {doc} */\nclass {name}(")?;
    for role in roles.keys() {
        writeln!(out, "    val {role}: Color,")?;
    }
    out.push_str(")\n");
    Ok(())
}

/// A constructor call with one named colour argument per role, one per line.
fn roles_value(out: &mut String, name: &str, roles: &Roles, indent: usize) -> std::fmt::Result {
    let pad = " ".repeat(indent);
    writeln!(out, "{pad}{name}(")?;
    for (role, colour) in roles {
        writeln!(out, "{pad}    {role} = {},", color(*colour))?;
    }
    writeln!(out, "{pad})")
}

fn color(colour: Argb) -> String {
    format!("Color(0x{:08X})", colour.0)
}
